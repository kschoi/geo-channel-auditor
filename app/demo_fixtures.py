"""데모(DEMO MOCK) 모드에서 사용하는 가상 Liner API 응답 픽스처.

`LINER_API_KEY`가 없을 때 UI와 진단 흐름을 그대로 체험할 수 있도록, Liner Search /
Search Agent / Router 세 API의 응답을 **같은 스키마**로 흉내 낸다. 실제 API 호출 경로와
응답 파싱 코드는 모드와 무관하게 동일하게 동작하며, 모의 지점은 이 파일의 데이터뿐이다.

모든 매장·수치·출처는 가상이며, 출처 URL은 실제 검색 결과 페이지(네이버·구글·다음)를
가리킨다. 제목 앞에 `[데모]`를 붙이고 `demo: True` 플래그를 두어, 데모 데이터임을
UI에서 구분해 표시한다.
"""

from __future__ import annotations

from typing import Any
from urllib.parse import quote

# --------------------------------------------------------------------------- #
# 공통 소스 헬퍼
# --------------------------------------------------------------------------- #

_FAVICON = "https://www.google.com/s2/favicons?domain={host}&sz=64"


def _source(kind: str, query: str, title: str, description: str, date: str) -> dict[str, Any]:
    """데모용 검색 출처 1건을 만든다. URL은 실제 검색 결과 페이지다."""
    if kind == "naver":
        url, host = f"https://search.naver.com/search.naver?query={quote(query)}", "search.naver.com"
    elif kind == "google":
        url, host = f"https://www.google.com/search?q={quote(query)}", "www.google.com"
    else:
        url, host = f"https://search.daum.net/search?q={quote(query)}", "search.daum.net"
    return {
        "title": f"[데모] {title}",
        "url": url,
        "hostname": host,
        "faviconUrl": _FAVICON.format(host=host),
        "description": description,
        "date": date,
        "demo": True,
    }


def _demo_search(query: str, items: list[tuple]) -> list[dict[str, Any]]:
    """(kind, title, description, date[, 검색어]) 튜플 목록을 출처로 변환한다.

    검색어를 생략하면 번들 쿼리를 쓴다. 한 번들 안에서 서로 다른 검색어를 재현할 때만
    5번째 값을 준다(URL 중복 방지).
    """
    sources = []
    for item in items:
        kind, title, desc, date = item[:4]
        item_query = item[4] if len(item) > 4 else query
        sources.append(_source(kind, item_query, title, desc, date))
    return sources


def _gap(
    gap_id: str,
    title: str,
    severity: str,
    dimension: str,
    reason: str,
    demand_evidence: str,
    source_urls: list[str],
    fix_hint: str,
) -> dict[str, Any]:
    return {
        "id": gap_id,
        "title": title,
        "severity": severity,
        "dimension": dimension,
        "reason": reason,
        "demand_evidence": demand_evidence,
        "source_urls": source_urls,
        "fix_hint": fix_hint,
    }


