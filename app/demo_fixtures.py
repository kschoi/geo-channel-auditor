def _coverage(text: str, keywords: list[str]) -> bool:
    return any(k in text for k in keywords)


def _demo_dimension_score(text: str, dimension: str) -> int:
    checks = [c for c in _INFO_CHECKS if c["dimension"] == dimension]
    if not checks:
        return 50
    covered = sum(1 for c in checks if _coverage(text, c["keywords"]))
    return round(30 + 60 * covered / len(checks))


